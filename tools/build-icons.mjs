// Builds every logo asset from one definition: the eye with a keyhole pupil
// inside a fading "thinking" ring of 12 lines.
//   cd tools && npm install && npm run icons
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BG = '#0B0B0F';
const ACCENT = '#A855F7';
const EYE = '#F2F2F5';

// Geometry in a 160×160 box centred on 0,0.
const LINES = 12;
const R_IN = 48, R_OUT = 62, STROKE = 6;
const opacity = (i) => +(1 - i * 0.075).toFixed(3); // 1 → 0.175 round the circle
const EYE_PATH = 'M-34 0Q0 -28 34 0Q0 28 -34 0Z';
const KEYHOLE = 'M0 -9.7A6.2 6.2 0 1 1 -0.01 -9.7ZM-3.2 0L3.2 0L5 11L-5 11Z';

function lineEnds(i) {
  const a = (i * 2 * Math.PI) / LINES;
  const p = (r) => [+(r * Math.sin(a)).toFixed(2), +(-r * Math.cos(a)).toFixed(2)];
  return [p(R_IN), p(R_OUT)];
}

// ---- SVG

function markSvg() {
  const lines = Array.from({ length: LINES }, (_, i) => {
    const [[x1, y1], [x2, y2]] = lineEnds(i);
    return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke-opacity="${opacity(i)}"/>`;
  }).join('');
  return `<g stroke="${ACCENT}" stroke-width="${STROKE}" stroke-linecap="round">${lines}</g>` +
    `<path d="${EYE_PATH}" fill="${EYE}"/><path d="${KEYHOLE}" fill="${BG}"/>`;
}

const svg = ({ tile = true, radius = 36 } = {}) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-80 -80 160 160">` +
  (tile ? `<rect x="-80" y="-80" width="160" height="160" rx="${radius}" fill="${BG}"/>` : '') +
  markSvg() + `</svg>\n`;

// ---- Android VectorDrawable (108dp adaptive-icon canvas, mark inside the 66dp safe zone)

function vectorDrawable(scale = 0.5) {
  const t = (x) => +(54 + x * scale).toFixed(2);
  const lines = Array.from({ length: LINES }, (_, i) => {
    const [[x1, y1], [x2, y2]] = lineEnds(i);
    return `    <path android:pathData="M${t(x1)},${t(y1)}L${t(x2)},${t(y2)}" android:strokeColor="${ACCENT}"
        android:strokeWidth="${STROKE * scale}" android:strokeLineCap="round" android:strokeAlpha="${opacity(i)}" />`;
  }).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build-icons.mjs — edit that file, not this one. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="54" android:translateY="54" android:scaleX="${scale}" android:scaleY="${scale}">
    <path android:fillColor="${EYE}" android:pathData="${EYE_PATH}" />
    <path android:fillColor="${BG}" android:pathData="${KEYHOLE}" />
  </group>
${lines}
</vector>
`;
}

function png(svgText, size) {
  return new Resvg(svgText, { fitTo: { mode: 'width', value: size } }).render().asPng();
}

async function out(path, data) {
  const full = join(root, path);
  await mkdir(dirname(full), { recursive: true });
  await writeFile(full, data);
  console.log(path);
}

// Master files
await out('brand/logo.svg', svg());
await out('brand/logo-mark.svg', svg({ tile: false }));
await out('brand/logo-1024.png', png(svg(), 1024));

// Website
await out('site/favicon.svg', svg({ radius: 36 }));
await out('site/apple-touch-icon.png', png(svg({ radius: 0 }), 180));
await out('site/icon-192.png', png(svg(), 192));
await out('site/assets/logo.svg', svg({ tile: false }));

// Android launcher icons (legacy, API < 26): rounded tile
const res = 'app/android/app/src/main/res';
for (const [dpi, size] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
  await out(`${res}/mipmap-${dpi}/ic_launcher.png`, png(svg(), size));
}
// Adaptive icon (API 26+) and Android 13 themed (monochrome) icon
await out(`${res}/drawable/ic_launcher_foreground.xml`, vectorDrawable());
await out(`${res}/values/ic_launcher_background.xml`,
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${BG}</color>\n</resources>\n`);
await out(`${res}/mipmap-anydpi-v26/ic_launcher.xml`, `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`);
